// Exercise 2.7.4: Experimenting with relational and logical operators
#include <stdio.h>

// Entry point of the program
int main(void)
{
    int x = 10, y = 20;

    printf("x < y: %d\n", x < y);
    printf("x > y: %d\n", x > y);
    printf("x && y: %d\n", x && y);
    printf("x || y: %d\n", x || y);

    return 0;
}
