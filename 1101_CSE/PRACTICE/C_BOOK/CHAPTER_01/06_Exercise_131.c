// Exercise 1.3.1: Compile and run Section 1.3 examples
#include <stdio.h>

// Demonstrates declaring variables of basic types
int main(void)
{
    int num = 100;
    char ch = 'X';
    float f = 100.123f;
    double d = 123.009;

    printf("num: %d, ch: %c, f: %f, d: %f\n", num, ch, f, d);

    return 0;
}
